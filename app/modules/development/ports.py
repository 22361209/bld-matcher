from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Callable, Protocol

from .document_ports import DevelopmentDocumentRepository


class DevelopmentRepository(Protocol):
    def get(self, kind: str, identifier: str) -> dict | None: ...
    def insert(self, kind: str, data: dict) -> None: ...
    def update(self, kind: str, identifier: str, data: dict) -> None: ...
    def claim_project(self, project_id: str, expected_version: object) -> dict: ...
    def export_aggregate(self, project_id: str) -> dict: ...
    def invalidate_confirmations(self, project_id: str, branch_ids: list[str] | None = None) -> None: ...
    def audit(self, action: str, project_id: str, detail: str, *, actor: str) -> None: ...
    def rows(self, kind: str, *, project_id: str | None = None) -> list[dict]: ...
    def copy_document_links(self, project_id: str, target_type: str, source_id: str, target_id: str, *, actor: str) -> None: ...


class DevelopmentUnitOfWork(Protocol):
    @property
    def repository(self) -> DevelopmentRepository: ...

    @property
    def documents(self) -> DevelopmentDocumentRepository: ...

    def commit(self) -> None: ...
    def begin(self) -> None: ...


UnitOfWorkFactory = Callable[[], AbstractContextManager[DevelopmentUnitOfWork]]
